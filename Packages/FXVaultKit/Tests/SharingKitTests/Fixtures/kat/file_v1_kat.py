"""Independent Python vectors for the `.fxvault` v1 file (SHARING-PROTOCOL.md §2).

The 64-byte header and AES-256-GCM under a fixed key (Argon2id is not re-run here), AAD =
header. 1.0 still opens these files, so Swift reproduces the file byte for byte. The values are
the ones `crosscheck.py` wrote into `nearby_kat.json` before 1.0 removed nearby sharing.

Usage (from a venv with `cryptography` installed):
  python3 file_v1_kat.py --lines                 # key=value lines
  python3 file_v1_kat.py --write file_v1_kat.json
"""

import json
import struct
import sys

from cryptography.hazmat.primitives.ciphers.aead import AESGCM


def fxvault_header(ops, mem_kib, salt, nonce):
    h = bytes([0x46, 0x58, 0x56, 0x41, 0x55, 0x4C, 0x54, 0x1A])
    h += struct.pack('>HH', 1, 64) + bytes([1, 1]) + struct.pack('>II', ops, mem_kib) + bytes([1, 0])
    h += salt + nonce
    return h + bytes(64 - len(h))


def vectors():
    key = bytes([0x42]) * 32
    salt = bytes(range(0x80, 0x90))
    nonce = bytes(range(0x90, 0x9c))
    header = fxvault_header(3, 65536, salt, nonce)
    payload = b'{"schema":"fxvault.share/1"}'
    ct_tag = AESGCM(key).encrypt(nonce, payload, header)
    assert AESGCM(key).decrypt(nonce, ct_tag, header) == payload
    inputs = {
        'fxvault_key': key.hex(), 'fxvault_opsLimit': 3, 'fxvault_memLimitKiB': 65536,
        'fxvault_salt': salt.hex(), 'fxvault_nonce': nonce.hex(), 'fxvault_payload_utf8': payload.decode(),
    }
    outputs = {
        'fxvault_ciphertext_and_tag': ct_tag.hex(),
        'fxvault_file_length': str(len(header) + len(ct_tag)),
        'fxvault_header': header.hex(),
    }
    return inputs, outputs


def main():
    inputs, outputs = vectors()
    if len(sys.argv) >= 3 and sys.argv[1] == '--write':
        document = {
            'description': 'FX Vault .fxvault v1 known-answer vectors. Generated by kat/file_v1_kat.py: '
                           'header and AES-256-GCM under a fixed key, byte for byte.',
            'inputs': inputs,
            'outputs': outputs,
        }
        with open(sys.argv[2], 'w') as handle:
            json.dump(document, handle, indent=2, sort_keys=True)
            handle.write('\n')
    else:
        for key in sorted(outputs):
            sys.stdout.write(f'{key}={outputs[key]}\n')


if __name__ == '__main__':
    main()
