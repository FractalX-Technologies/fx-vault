// MARK: - Hex and fixtures

extension Data {
    init?(hex: String) {
        guard hex.count.isMultiple(of: 2) else { return nil }
        var bytes: [UInt8] = []
        var index = hex.startIndex
        while index < hex.endIndex {
            let next = hex.index(index, offsetBy: 2)
            guard let byte = UInt8(hex[index..<next], radix: 16) else { return nil }
            bytes.append(byte)
            index = next
        }
        self.init(bytes)
    }

    var hex: String {
        map { String(format: "%02x", $0) }.joined()
    }
}

enum Fixtures {
    static func url(_ path: String) throws -> URL {
        let root = try #require(Bundle.module.url(forResource: "Fixtures", withExtension: nil))
        return root.appendingPathComponent(path)
    }

    static func data(_ path: String) throws -> Data {
        try Data(contentsOf: url(path))
    }
}

/// The pinned vectors in Fixtures/nearby_kat.json (generated by kat/crosscheck.py and checked
/// against kat/NearbyProtocolReference.swift).
struct NearbyKAT: Decodable {
    struct Inputs: Decodable {
        let skI: String
        let skR: String
        let nI: String
        let nR: String
        let nameI: String
        let nameR: String
        let nameR_altered: String
        let fxvault_key: String
        let fxvault_opsLimit: UInt32
        let fxvault_memLimitKiB: UInt32
        let fxvault_salt: String
        let fxvault_nonce: String
        let fxvault_payload_utf8: String
    }

    let inputs: Inputs
    let outputs: [String: String]

    static func load() throws -> NearbyKAT {
        try JSONDecoder().decode(NearbyKAT.self, from: Fixtures.data("nearby_kat.json"))
    }

    func output(_ key: String) throws -> String {
        try #require(outputs[key])
    }

    func bytes(_ hex: String) throws -> Data {
        try #require(Data(hex: hex))
    }

    func keyMaterial(_ role: NearbyRole) throws -> NearbyKeyMaterial {
        let secret = try bytes(role == .initiator ? inputs.skI : inputs.skR)
        let nonce = try bytes(role == .initiator ? inputs.nI : inputs.nR)
        let key = try Curve25519.KeyAgreement.PrivateKey(rawRepresentation: secret)
        return NearbyKeyMaterial(privateKey: key, nonce: nonce)
    }
}

// MARK: - Deterministic randomness

/// SplitMix64, for reproducible "random" draws in tests.
struct SeededGenerator: RandomNumberGenerator {
    private var state: UInt64

    init(seed: UInt64) {
        state = seed
    }

    mutating func next() -> UInt64 {
        state &+= 0x9E37_79B9_7F4A_7C15
        var value = state
        value = (value ^ (value >> 30)) &* 0xBF58_476D_1CE4_E5B9
        value = (value ^ (value >> 27)) &* 0x94D0_49BB_1331_11EB
        return value ^ (value >> 31)
    }
}

// MARK: - Key derivation fakes

/// Returns SHA-256(passphrase ‖ salt ‖ t ‖ m): deterministic, passphrase-dependent, instant.
struct FakeKeyDeriver: KeyDeriving {
    func deriveKey(passphrase: SecretBytes, parameters: KeyDerivationParametersModel) async throws -> SecretBytes {
        var hasher = SHA256()
        passphrase.withUnsafeBytes { hasher.update(bufferPointer: $0) }
        hasher.update(data: parameters.salt)
        hasher.update(data: Data("\(parameters.opsLimit)/\(parameters.memLimitKiB)".utf8))
        return SecretBytes(copying: Array(hasher.finalize()))
    }
}

/// Always returns the same key (the KAT key 0x42 × 32).
struct FixedKeyDeriver: KeyDeriving {
    let key: Data

    func deriveKey(passphrase: SecretBytes, parameters: KeyDerivationParametersModel) async throws -> SecretBytes {
        SecretBytes(key)
    }
}

/// Counts calls; proves bounds are checked before the KDF.
final class SpyKeyDeriver: KeyDeriving {
    private let calls = OSAllocatedUnfairLock(initialState: 0)

    var callCount: Int {
        calls.withLock { $0 }
    }

    func deriveKey(passphrase: SecretBytes, parameters: KeyDerivationParametersModel) async throws -> SecretBytes {
        calls.withLock { $0 += 1 }
        return try await FakeKeyDeriver().deriveKey(passphrase: passphrase, parameters: parameters)
    }
}

/// Throws CancellationError.
struct CancellingKeyDeriver: KeyDeriving {
    func deriveKey(passphrase: SecretBytes, parameters: KeyDerivationParametersModel) async throws -> SecretBytes {
        throw CancellationError()
    }
}

