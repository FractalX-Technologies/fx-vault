// MARK: - Async helpers

extension AsyncStream {
    /// Collects elements until the stream finishes.
    func collect() async -> [Element] {
        var result: [Element] = []
        for await element in self {
            result.append(element)
        }
        return result
    }
}

/// Reads events one at a time from a stream.
final class EventReader<Element: Sendable>: @unchecked Sendable {
    private var iterator: AsyncStream<Element>.Iterator

    init(_ stream: AsyncStream<Element>) {
        iterator = stream.makeAsyncIterator()
    }

    func next() async -> Element? {
        await iterator.next()
    }

    /// Skips events until `predicate` matches; nil if the stream ends first.
    func first(where predicate: (Element) -> Bool) async -> Element? {
        while let element = await iterator.next() {
            if predicate(element) { return element }
        }
        return nil
    }

    /// The remaining events until the stream finishes.
    func rest() async -> [Element] {
        var result: [Element] = []
        while let element = await iterator.next() {
            result.append(element)
        }
        return result
    }
}

extension NearbyEvent {
    var sasModel: NearbySASModel? {
        if case .sasReady(let model) = self { return model }
        return nil
    }

    var abortModel: NearbyAbortModel? {
        if case .aborted(let model) = self { return model }
        return nil
    }

    var isAbort: Bool {
        abortModel != nil
    }

    var isTerminal: Bool {
        switch self {
        case .aborted, .completed: true
        default: false
        }
    }
}

extension NearbyStep {
    var abortReason: NearbyAbortReason? {
        events.compactMap(\.abortModel).first?.reason
    }
}
